#!/usr/bin/env node
/**
 * Motion Wave — generate the grain engine's window tables and their moments.
 *
 * `lib-grain-engine.md` §3 says the moments are "read from the generated tables
 * rather than from a closed form, so the constant the normalisation uses and the
 * table the audio reads cannot drift apart", and names getting this wrong as the
 * most common failure in granular code: the device gets louder as density rises,
 * the user trims the output, and then the feedback loop's gain changes with
 * density and the reverb runs away.
 *
 * So both come out of here, and the moments are integrated from the *emitted*
 * samples rather than from the formula that produced them. A table edited by
 * hand would move its own constants with it, which is the only way this stays
 * true rather than merely being true today.
 *
 * Only Hann and Gaussian are tabulated. Tukey is a Hann taper with a flat
 * middle, so it is a phase remap of the same table — which is also what makes
 * Tukey(α=1) equal Hann bit-for-bit, as GE-01 requires — and Rectangular is 1.
 * Their moments have exact closed forms in terms of Hann's and are emitted as
 * expressions, not as separate numbers to drift.
 *
 * Run with `--check` to fail when the header on disk is stale.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const target = join(here, '..', 'motionwave', 'core', 'dsp', 'grain', 'window_tables.gen.h');

/**
 * Points per window, plus one guard sample so a linear interpolation at phase
 * 1.0 reads `table[N]` rather than running off the end. 2048 puts the
 * interpolation error below a float32 step for every window here.
 */
const N = 2048;

/** Gaussian truncation, in standard deviations at the window's edge. */
const GAUSSIAN_SIGMA = 2.5;

function hann(x) {
  return 0.5 - 0.5 * Math.cos(2 * Math.PI * x);
}

function gaussian(x) {
  const t = GAUSSIAN_SIGMA * (2 * x - 1);
  return Math.exp(-0.5 * t * t);
}

/** Sample a shape onto N+1 points, as float32 — the precision the audio has. */
function tabulate(fn) {
  const out = new Float32Array(N + 1);
  for (let i = 0; i <= N; i++) out[i] = Math.fround(fn(i / N));
  return out;
}

/**
 * Mean of a tabulated window, and of its square.
 *
 * Trapezoidal over the emitted float32 samples. Integrating the closed form
 * instead would give a prettier number and would stop describing the table.
 */
function moments(table) {
  let sum = 0;
  let sumSquare = 0;
  for (let i = 0; i < N; i++) {
    const a = table[i];
    const b = table[i + 1];
    sum += 0.5 * (a + b);
    sumSquare += 0.5 * (a * a + b * b);
  }
  return { mean: sum / N, meanSquare: sumSquare / N };
}

function emitTable(name, table) {
  const rows = [];
  for (let i = 0; i <= N; i += 8) {
    const slice = [];
    for (let k = i; k < Math.min(i + 8, N + 1); k++) {
      slice.push(`${table[k].toPrecision(9)}f`);
    }
    rows.push(`    ${slice.join(', ')},`);
  }
  return `inline constexpr float ${name}[kWindowPoints + 1] = {\n${rows.join('\n')}\n};\n`;
}

const hannTable = tabulate(hann);
const gaussianTable = tabulate(gaussian);
const hannMoments = moments(hannTable);
const gaussianMoments = moments(gaussianTable);

const header = `// GENERATED by scripts/generate-window-tables.mjs — do not edit.
//
// The grain engine's window tables and the moments its amplitude normalisation
// depends on. Both come from one generator so that a table and the constant
// describing it cannot drift apart; the moments are integrated from the emitted
// float32 samples rather than from the closed form, so editing a sample by hand
// moves its own constant with it.
//
// \`lib-grain-engine.md\` §3 and §5.3.
#pragma once

namespace mw::dsp::grain {

/// Points per window. One guard sample follows, so a linear interpolation at
/// phase 1.0 reads the guard rather than running off the end.
inline constexpr int kWindowPoints = ${N};

/// Standard deviations at the Gaussian window's edge.
inline constexpr float kGaussianSigma = ${GAUSSIAN_SIGMA}f;

${emitTable('kHannWindow', hannTable)}
${emitTable('kGaussianWindow', gaussianTable)}
/// Integrated from the tables above. Hann's closed forms are 0.5 and 0.375;
/// these are what the shipped samples actually average to, which is the number
/// the normalisation must use.
inline constexpr float kHannMean = ${hannMoments.mean.toPrecision(9)}f;
inline constexpr float kHannMeanSquare = ${hannMoments.meanSquare.toPrecision(9)}f;
inline constexpr float kGaussianMean = ${gaussianMoments.mean.toPrecision(9)}f;
inline constexpr float kGaussianMeanSquare = ${gaussianMoments.meanSquare.toPrecision(9)}f;

}  // namespace mw::dsp::grain
`;

/**
 * Compared with line endings normalised.
 *
 * `.gitattributes` sets `eol=lf` for exactly this reason, and it is not enough:
 * a working tree checked out before that line was added keeps its carriage
 * returns, and then a generated file differs from its own generator by nothing
 * at all and the check calls it stale. That happened here, to both grain
 * tables, and it went unnoticed for as long as it did because nothing ran
 * either check. A guarantee that a generated file matches its source cannot
 * depend on which platform is asking.
 */
const sameContent = (a, b) => a.split('\r\n').join('\n') === b.split('\r\n').join('\n');

const check = process.argv.includes('--check');
let existing = null;
try {
  existing = readFileSync(target, 'utf8');
} catch {
  existing = null;
}
if (check) {
  if (existing === null || !sameContent(existing, header)) {
    console.error(`window tables: ${target} is stale — run \`npm run windows\``);
    process.exit(1);
  }
  console.log('window tables: up to date');
} else if (existing !== header) {
  writeFileSync(target, header);
  console.log(`wrote ${target}`);
} else {
  console.log('window tables: up to date');
}
