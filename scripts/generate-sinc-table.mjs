// Emits the grain engine's rate-scaled interpolation kernel.
//
// Why this exists rather than a one-pole: fx-02 §3.1's stated remedy for the
// aliasing an upward shift folds back is "a one-pole lowpass at 0.45·fs/r
// before the read", and that value is marked [I] — an emulator's choice, not a
// measurement, which LEGAL_NOTES.md quarantines. Re-deriving it showed it also
// cannot work. Reading a buffer at increment r moves source content at f to
// f·r, so everything above fs/(2r) folds; at the Wide set's +19 semitones that
// corner is 8008 Hz, and §9 V12 excites it with a 10 kHz tone only 0.32
// octaves above. A one-pole gives 6 dB per octave, so it delivers about 2 dB
// where V12 asks for 70. The sheet's own remedy cannot meet the sheet's own
// tolerance, which is the clearest evidence available that the [I] figure came
// from an implementation that did not meet it either.
//
// What does work is scaling the *interpolation kernel* instead of filtering
// ahead of it, which costs no extra pass over the data. A windowed sinc of
// half-width W has its cutoff at Nyquist; the same prototype evaluated at x/r
// is a kernel whose cutoff is fs/(2r), which is exactly the anti-imaging filter
// the resampling needs. One prototype therefore serves every rate, which is why
// this table is a single curve rather than one per interval.
import { writeFileSync, readFileSync } from 'node:fs';

const HALF_WIDTH = 8;      // lobes either side; sets the stopband depth
const STEPS = 512;         // samples of the prototype per unit of x
const COUNT = HALF_WIDTH * STEPS + 1;

// Blackman-Harris over the kernel's support, for the same reason the analysis
// windows use it: its far sidelobes are what the stopband depth actually is.
function prototype(x) {
  if (x >= HALF_WIDTH) return 0;
  const sinc = x === 0 ? 1 : Math.sin(Math.PI * x) / (Math.PI * x);
  const t = (x / HALF_WIDTH + 1) * 0.5;           // 0.5 at the centre, 1 at the edge
  const w =
    0.35875 -
    0.48829 * Math.cos(2 * Math.PI * t) +
    0.14128 * Math.cos(4 * Math.PI * t) -
    0.01168 * Math.cos(6 * Math.PI * t);
  return sinc * w;
}

const samples = [];
for (let i = 0; i < COUNT; ++i) samples.push(Math.fround(prototype(i / STEPS)));

const lines = [];
lines.push('// GENERATED by scripts/generate-sinc-table.mjs — do not edit.');
lines.push('//');
lines.push('// The rate-scaled interpolation kernel. See the generator for why a one-pole');
lines.push('// at 0.45·fs/r was rejected rather than copied: it is an [I] value, and 6 dB');
lines.push('// per octave cannot deliver the 70 dB fx-02 §9 V12 grades 0.32 octaves above');
lines.push('// the fold corner. This is a prototype sinc windowed by Blackman-Harris,');
lines.push('// sampled ' + STEPS + ' times per unit; evaluating it at x/r yields the kernel whose');
lines.push('// cutoff is fs/(2r), so one curve serves every pitch ratio.');
lines.push('#pragma once');
lines.push('');
lines.push('namespace mw::dsp::grain {');
lines.push('');
lines.push('/// Lobes either side of centre. The kernel spans 2·W·r source samples.');
lines.push(`inline constexpr int kSincHalfWidth = ${HALF_WIDTH};`);
lines.push('/// Prototype samples per unit of x, so the table index is x·this.');
lines.push(`inline constexpr int kSincStepsPerUnit = ${STEPS};`);
lines.push(`inline constexpr int kSincTablePoints = ${COUNT};`);
lines.push('');
lines.push('/// One guard entry is unnecessary here because the prototype is exactly zero');
lines.push('/// at its edge, so an interpolation that runs off the end reads a true zero.');
lines.push(`inline constexpr float kSincPrototype[kSincTablePoints] = {`);
for (let i = 0; i < COUNT; i += 8) {
  lines.push('    ' + samples.slice(i, i + 8).map((v) => `${v.toPrecision(9)}f`).join(', ') + ',');
}
lines.push('};');
lines.push('');
lines.push('}  // namespace mw::dsp::grain');
lines.push('');

const text = lines.join('\n');
const target = 'motionwave/core/dsp/grain/sinc_table.gen.h';
if (process.argv.includes('--check')) {
  const have = readFileSync(target, 'utf8');
  if (have !== text) {
    console.error(`${target} is out of date — run: npm run sinc`);
    process.exit(1);
  }
  console.log(`${target} is up to date`);
} else {
  writeFileSync(target, text);
  console.log(`wrote ${target} (${COUNT} points)`);
}
